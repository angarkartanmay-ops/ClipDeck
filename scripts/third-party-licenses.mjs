// Regenerates THIRD_PARTY_LICENSES.md from `cargo metadata` (every shipped
// target, normal dependencies only) and the npm packages bundled into the
// dashboard.
// Usage: node scripts/third-party-licenses.mjs

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const TARGETS = [
  ["x86_64-pc-windows-msvc", "Windows"],
  ["aarch64-pc-windows-msvc", "Windows"],
  ["x86_64-apple-darwin", "macOS"],
  ["aarch64-apple-darwin", "macOS"],
  ["x86_64-unknown-linux-gnu", "Linux"],
];

// name@version -> { name, version, license, repo, platforms }
const crates = new Map();

for (const [target, os] of TARGETS) {
  const meta = JSON.parse(
    execFileSync(
      "cargo",
      ["metadata", "--format-version", "1", "--manifest-path", "src-tauri/Cargo.toml", "--filter-platform", target],
      { maxBuffer: 256 * 1024 * 1024 },
    ),
  );

  // Walk only normal (non-dev, non-build) dependency edges from the root crate.
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
  const seen = new Set();
  const stack = [meta.resolve.root];
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
    }
  }
  seen.delete(meta.resolve.root);

  for (const p of [...seen].map((id) => pkgs.get(id))) {
    const key = `${p.name}@${p.version}`;
    const entry = crates.get(key) ?? {
      name: p.name,
      version: p.version,
      license: p.license ?? "(see crate)",
      repo: p.repository ?? "",
      platforms: new Set(),
    };
    entry.platforms.add(os);
    crates.set(key, entry);
  }
}

const ORDER = ["Windows", "macOS", "Linux"];
const rust = [...crates.values()]
  .map((c) => ({
    ...c,
    platforms: c.platforms.size === ORDER.length ? "All" : ORDER.filter((o) => c.platforms.has(o)).join(", "),
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const npm = ["@tauri-apps/api", "@fontsource-variable/mona-sans", "@fontsource-variable/hubot-sans", "@fontsource-variable/martian-mono"].map((name) => {
  const pkg = JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8"));
  return { name, version: pkg.version, license: pkg.license, repo: (pkg.repository?.url ?? pkg.repository ?? "").replace(/^git\+/, "") };
});

const counts = {};
for (const d of rust) counts[d.license] = (counts[d.license] ?? 0) + 1;

const out = `# Third-party licenses

ClipDeck is built with the open source components listed below. Each is
distributed under its own license; their copyright notices and license texts
are available in each project's repository and in the crate/package sources.
No GPL, AGPL or LGPL code is compiled into ClipDeck on any platform; this is
enforced in CI by \`cargo deny\` (see \`src-tauri/deny.toml\`) and
\`npm run licenses\`.

The Mona Sans and Hubot Sans typefaces (GitHub) and Martian Mono (Evil
Martians) are bundled under the SIL Open Font License 1.1, which permits
embedding them in software.

The bundled SQLite library (via \`libsqlite3-sys\`) is in the public domain.

Generated by \`node scripts/third-party-licenses.mjs\`.

## Web view and system libraries

ClipDeck draws its window with the web view the operating system provides and
does not include a browser engine of its own:

- **Windows**: Microsoft Edge WebView2 Runtime, part of Windows 11 or installed
  separately under Microsoft's terms. Not redistributed by ClipDeck.
- **macOS**: WKWebView, part of macOS.
- **Linux (.deb, .rpm)**: the distribution's WebKitGTK, GTK and GLib
  (LGPL-2.1-or-later), installed as package dependencies and dynamically
  linked. Not redistributed by ClipDeck.
- **Linux (.AppImage)**: so it runs without installing anything, the AppImage
  carries unmodified copies of WebKitGTK, GTK, GLib and the libraries they
  need, taken from Ubuntu 22.04. They stay separate shared libraries inside
  the image, so they can be replaced, and keep their own licenses (mostly
  LGPL-2.1-or-later). Their source code is in the Ubuntu 22.04 source archive
  (https://launchpad.net/ubuntu/jammy) and with each project.

## License summary (Rust crates, all platforms)

| License expression | Crates |
| --- | --- |
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([l, n]) => `| ${l} | ${n} |`).join("\n")}

## Dashboard (npm, bundled)

| Package | Version | License | Source |
| --- | --- | --- | --- |
${npm.map((d) => `| ${d.name} | ${d.version} | ${d.license} | ${d.repo} |`).join("\n")}

## Rust crates

| Crate | Version | License | Platforms | Source |
| --- | --- | --- | --- | --- |
${rust.map((d) => `| ${d.name} | ${d.version} | ${d.license} | ${d.platforms} | ${d.repo} |`).join("\n")}
`;
writeFileSync("THIRD_PARTY_LICENSES.md", out);
console.log(`wrote THIRD_PARTY_LICENSES.md: ${rust.length} crates, ${npm.length} npm packages`);
