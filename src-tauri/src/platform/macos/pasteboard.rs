//! The macOS general pasteboard: watching for changes, reading and writing.
//!
//! macOS has no clipboard-change notification, so ClipDeck compares the
//! pasteboard's `changeCount` a few times a second. That is a single integer
//! read and never touches clipboard contents; contents are read only after a
//! change, and only when capture is allowed.

use std::sync::atomic::{AtomicIsize, Ordering};
use std::sync::mpsc::Sender;
use std::sync::Arc;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use objc2::rc::{autoreleasepool, Retained};
use objc2::runtime::{NSObjectProtocol, ProtocolObject};
use objc2::sel;
use objc2_app_kit::{NSPasteboard, NSPasteboardWriting, NSWorkspace};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};
use tauri::{AppHandle, Manager};

use crate::clip::{
    ClipData, ClipFormat, ReadOptions, ReadOutcome, MAC_FILES, MAC_HTML, MAC_PNG, MAC_RTF,
    MAC_TEXT, MAC_TIFF,
};
use crate::state::AppState;
use crate::worker::Job;

/// Markers that password managers and other tools put on the pasteboard to
/// keep an item out of clipboard history (see nspasteboard.org).
const CONCEALED: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
];

const POLL: Duration = Duration::from_millis(350);

/// `changeCount` right after ClipDeck itself wrote the pasteboard.
static SELF_WRITE: AtomicIsize = AtomicIsize::new(-1);

fn pasteboard() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// macOS 15.4+ lets the user decide per app whether it may read the
/// pasteboard. Returns true when reading would be refused or prompt.
pub fn access_restricted() -> bool {
    autoreleasepool(|_| {
        let pb = pasteboard();
        if !pb.respondsToSelector(sel!(accessBehavior)) {
            return false;
        }
        // 1 = ask every time, 3 = always deny.
        matches!(pb.accessBehavior().0, 1 | 3)
    })
}

/// Starts the change watcher on its own thread.
pub fn watch(app: AppHandle, jobs: Sender<Job>) {
    std::thread::Builder::new()
        .name("clipdeck-pasteboard".into())
        .spawn(move || {
            let mut last = autoreleasepool(|_| pasteboard().changeCount());
            loop {
                std::thread::sleep(POLL);
                let count = autoreleasepool(|_| pasteboard().changeCount());
                if count == last {
                    continue;
                }
                last = count;
                if count == SELF_WRITE.load(Ordering::Acquire) {
                    continue; // ClipDeck's own paste
                }
                autoreleasepool(|_| capture(&app, &jobs));
            }
        })
        .expect("spawn pasteboard watcher");
}

fn capture(app: &AppHandle, jobs: &Sender<Job>) {
    let state = app.state::<Arc<AppState>>().inner().clone();
    if !state.capture_allowed() || access_restricted() {
        return;
    }
    let (source_id, source_name) = frontmost_app().unwrap_or_default();
    let settings = state.settings();
    if settings.is_blocked(&source_id) || settings.is_blocked(&source_name) {
        return;
    }
    let opts = ReadOptions {
        images: settings.capture_images,
        files: settings.capture_files,
        rich: settings.capture_rich,
        max_bytes: settings.max_item_bytes(),
    };
    match read(&opts) {
        Ok(ReadOutcome::Data(data)) => {
            let created_at = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map(|d| d.as_millis() as i64)
                .unwrap_or_default();
            let _ = jobs.send(Job::Capture {
                data,
                created_at,
                source_exe: source_id,
                source_name,
            });
        }
        Ok(_) => {}
        Err(err) => eprintln!("ClipDeck: capture: {err}"),
    }
}

/// The app in front: (lower-case bundle id, display name).
pub fn frontmost_app() -> Option<(String, String)> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    let id = app
        .bundleIdentifier()
        .map(|s| s.to_string().to_lowercase())
        .unwrap_or_default();
    let name = app
        .localizedName()
        .map(|s| s.to_string())
        .unwrap_or_default();
    Some((id, name))
}

fn file_urls(pb: &NSPasteboard) -> Vec<String> {
    let kind = NSString::from_str(MAC_FILES);
    pb.pasteboardItems()
        .map(|items| {
            items
                .iter()
                .filter_map(|item| item.stringForType(&kind))
                .map(|url| url.to_string())
                .collect()
        })
        .unwrap_or_default()
}

pub fn read(opts: &ReadOptions) -> Result<ReadOutcome, String> {
    let pb = pasteboard();
    let types: Vec<String> = pb
        .types()
        .map(|types| types.iter().map(|t| t.to_string()).collect())
        .unwrap_or_default();
    if types.iter().any(|t| CONCEALED.contains(&t.as_str())) {
        return Ok(ReadOutcome::Excluded);
    }
    let has = |kind: &str| types.iter().any(|t| t == kind);

    let mut budget = opts.max_bytes;
    let mut formats: Vec<ClipFormat> = Vec::new();
    let mut push = |kind: &str, formats: &mut Vec<ClipFormat>| {
        if !has(kind) {
            return;
        }
        let Some(data) = pb.dataForType(&NSString::from_str(kind)) else {
            return;
        };
        if data.is_empty() || data.len() > budget {
            return;
        }
        let bytes = data.to_vec();
        budget = budget.saturating_sub(bytes.len());
        formats.push(ClipFormat {
            name: kind.into(),
            data: bytes,
        });
    };

    if has(MAC_FILES) {
        if !opts.files {
            return Ok(ReadOutcome::Empty);
        }
        let urls = file_urls(&pb);
        if !urls.is_empty() {
            formats.push(ClipFormat {
                name: MAC_FILES.into(),
                data: urls.join("\n").into_bytes(),
            });
        }
        push(MAC_TEXT, &mut formats);
    } else {
        push(MAC_TEXT, &mut formats);
        if opts.rich {
            push(MAC_HTML, &mut formats);
            push(MAC_RTF, &mut formats);
        }
        if opts.images {
            push(MAC_PNG, &mut formats);
            // TIFF is large; keep it only when there is no PNG.
            if !has(MAC_PNG) {
                push(MAC_TIFF, &mut formats);
            }
        }
    }

    let has_text = formats
        .iter()
        .any(|f| f.name == MAC_TEXT && !String::from_utf8_lossy(&f.data).trim().is_empty());
    let has_payload = has_text
        || formats
            .iter()
            .any(|f| matches!(f.name.as_str(), MAC_PNG | MAC_TIFF | MAC_FILES));
    if !has_payload {
        return Ok(ReadOutcome::Empty);
    }
    Ok(ReadOutcome::Data(ClipData { formats }))
}

pub fn write(data: &ClipData) -> Result<(), String> {
    autoreleasepool(|_| {
        let pb = pasteboard();
        // Claim the coming change before it happens, so the watcher can never
        // see ClipDeck's own write as a new copy.
        SELF_WRITE.store(pb.changeCount() + 1, Ordering::Release);
        let count = pb.clearContents();
        SELF_WRITE.store(count, Ordering::Release);
        if let Some(list) = data.get(MAC_FILES) {
            let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
                String::from_utf8_lossy(list)
                    .lines()
                    .filter_map(|line| NSURL::URLWithString(&NSString::from_str(line.trim())))
                    .map(ProtocolObject::from_retained)
                    .collect();
            if !urls.is_empty() {
                pb.writeObjects(&NSArray::from_retained_slice(&urls));
            }
        }
        for format in &data.formats {
            if format.name == MAC_FILES {
                continue;
            }
            let bytes = NSData::with_bytes(&format.data);
            pb.setData_forType(Some(&bytes), &NSString::from_str(&format.name));
        }
        SELF_WRITE.store(pb.changeCount(), Ordering::Release);
        Ok(())
    })
}
